export function buildSensors(): SensorNode[] {
  const types: SensorNode['type'][] = ['Rain gauge', 'Soil moisture', 'GNSS', 'Piezometer', 'AWS', 'InSAR proxy']
  const units: Record<SensorNode['type'], string> = {
    'Rain gauge': 'mm/h',
    'Soil moisture': '%',
    GNSS: 'mm',
    Piezometer: 'kPa',
    AWS: 'mm',
    'InSAR proxy': 'mm/yr',
  }
  return ZONE_SEEDS.flatMap((z, zi) =>
    types.slice(0, 3 + (zi % 3)).map((type, ti) => ({
      id: `S-${z.id}-${ti}`,
      name: `${type} · ${z.district}`,
      type,
      zoneId: z.id,
      lat: z.lat + (ti - 1) * 0.012,
      lng: z.lng + (ti % 2 === 0 ? 0.014 : -0.01),
      value: 0,
      unit: units[type],
      status: 'Online' as const,
      battery: 72 + ((zi + ti) % 24),
    })),
  )
}
